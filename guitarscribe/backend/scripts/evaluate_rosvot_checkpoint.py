"""Inspect locally generated ROSVOT outputs; never repair model predictions."""
import hashlib
import json
from pathlib import Path
import sys
import numpy as np
import soundfile as sf
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from scripts.inspect_external_midi import inspect
from scripts.evaluate_onset_candidate import gate

ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'output/evaluation'
OUT=BASE/'rosvot-checkpoint-2026-10-25'

def write(path,data):path.write_text(json.dumps(data,indent=2,allow_nan=False)+'\n')
def stats(notes):
    durations=[n['end']-n['start'] for n in notes]
    return dict(notes=len(notes),under_100ms=sum(d<.1 for d in durations),under_10ms=sum(d<.01 for d in durations),voiced_seconds=sum(durations),median_duration=float(np.median(durations)) if durations else None)

def decode_events(raw):
    """Model pitch zero is a rest; it still advances the cumulative timeline."""
    if len(raw['pitches'])!=len(raw['note_durs']):
        raise ValueError('Pitch/duration lengths differ')
    notes=[];rests=[];time=0.
    for pitch,dur in zip(raw['pitches'],raw['note_durs']):
        if not np.isfinite(dur) or dur<=0 or not np.isfinite(pitch) or int(pitch)!=pitch or not 0<=pitch<=127:
            raise ValueError('Invalid model event')
        event=dict(start=time,end=time+float(dur),midi=int(pitch))
        (notes if pitch else rests).append(event)
        time+=float(dur)
    return notes,rests,time

def main():
    items=json.loads((OUT/'inputs.json').read_text())
    hashes=json.loads((OUT/'input-hashes.json').read_text())
    baselines={'third-1':BASE/'third-source-2026-10-25/g-1.json','third-2':BASE/'third-source-2026-10-25/g-2.json','saved-G':BASE/'external-comparison-2026-10-25/baseline-2.json','live':BASE/'external-comparison-2026-10-25/baseline-1.json'}
    report=dict(status='engineering_only_not_human_accepted',method='ROSVOT official defaults, automatic RWBD, CPU device patch',cases=[])
    for item in items:
        name=item['item_name'];source=Path(item['wav_fn']);assert hashlib.sha256(source.read_bytes()).hexdigest()==hashes[name]
        duration=sf.info(source).duration
        # This pickle is generated by our local inference, not user-supplied data.
        raw=np.load(OUT/f'raw/npy/[note]{name}.npy',allow_pickle=True).item()
        notes,rests,time=decode_events(raw)
        # Official mel framing may differ from input by one frame; retain raw tails.
        assert abs(time-duration)<=128/24000+.0001,(name,time,duration)
        midi,midi_report=inspect(OUT/f'raw/midi/{name}.mid')
        assert not midi_report['parse_errors'] and len(midi)==len(notes)
        errors=[]
        for n,m in zip(notes,midi):
            assert n['midi']==m['midi']
            error=max(abs(n['start']-m['start']),abs(n['end']-m['end']))
            assert error<=m['onset_tick_seconds']+.000001
            errors.append(error)
        write(OUT/f'{name}-notes.json',notes)
        case=dict(id=name,input_seconds=duration,output_seconds=time,raw_stats=stats(notes),rest_intervals=rests,midi_parity=True,midi_max_error=max(errors,default=0),source_sha256=hashes[name])
        if name in baselines:
            baseline=json.loads(baselines[name].read_text());case['G_stats']=stats(baseline)
            step=.01;t=np.arange(0,duration,step)
            def pitches(events):
                x=np.full(len(t),-1,dtype=int)
                for n in events:x[(t>=n['start'])&(t<n['end'])]=n['midi']
                return x
            a,b=pitches(baseline),pitches(notes);both=(a>=0)&(b>=0)
            case['comparison_not_accuracy']=dict(both_voiced_seconds=float(both.sum()*step),pitch_equal_seconds=float((both&(a==b)).sum()*step),octave_difference_seconds=float((both&(abs(a-b)==12)).sum()*step),G_only_seconds=float(((a>=0)&(b<0)).sum()*step),model_only_seconds=float(((a<0)&(b>=0)).sum()*step))
        else:
            refname='B02-harmonic' if name=='control-harmonic' else 'C02-sustained-vibrato'
            reference=json.loads((BASE/f'onset-boundary-checkpoint-2026-10-25/{refname}-reference.json').read_text())
            case['independent_control']=gate(reference,notes)
            case['control_limit']='Synthetic tones are out of vocal training domain; report strict failures without tuning.'
        report['cases'].append(case)
    write(OUT/'report.json',report);print(json.dumps(report,indent=2))
if __name__=='__main__':main()
